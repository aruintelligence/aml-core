"""Reproducible synthetic enterprise exercise with real witness child processes.

All keys are freshly generated by this demo. The resulting pins are NOT an
independently provisioned external trust root or proof of production execution.
"""
import argparse
import json
import pathlib
import select
import socket
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
ROOT=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from authenticated_publication import sign_checkpoint
from signed_history import SignedHistory,digest
from trust_enrollment import propose
from witness_live_verifier import verify_live
from verify_trusted import sha
from enterprise_demo import run as create_bundle,public_hex

def execute(output):
    output=pathlib.Path(output)
    output.mkdir(parents=True,exist_ok=True)
    create_bundle(output)
    bundle=json.loads((output/"bundle.json").read_text())
    report=json.loads((output/"report.json").read_text())
    manifest={"schema":"AML-SEF2-TRUST-MANIFEST-V1",
        "public_keys":bundle["public_keys"],"bundle_sha256":sha(bundle),
        "report_sha256":sha(report)}
    (output/"manifest.json").write_text(json.dumps(manifest,sort_keys=True))
    approver=Ed25519PrivateKey.generate()
    history=SignedHistory(str(output/"history.sqlite"),approver.public_key())
    if history.append(propose(approver,1,bundle["public_keys"]))!="ENROLLED":
        raise AssertionError("signed history enrollment failed")
    cp=history.checkpoint()
    (output/"checkpoint.json").write_text(json.dumps(cp,sort_keys=True))
    witness_keys={}
    receipts=[]
    children=[]
    urls=[]
    controls={}
    with tempfile.TemporaryDirectory(prefix="aml-sef2-witness-") as temp:
        root=pathlib.Path(temp)
        approver_file=root/"approver.pub"
        approver_file.write_text(public_hex(approver))
        try:
            for name in ("north","south"):
                key=Ed25519PrivateKey.generate()
                witness_keys[name]=public_hex(key)
                secret=root/(name+".key")
                secret.write_text(key.private_bytes_raw().hex())
                secret.chmod(0o600)
                with socket.socket() as sock:
                    sock.bind(("127.0.0.1",0))
                    port=sock.getsockname()[1]
                child=subprocess.Popen([sys.executable,"-u",str(ROOT/"witness_http_service.py"),
                    "--db",str(root/(name+".sqlite")),"--witness-id",name,
                    "--private-key-file",str(secret),"--approver-public-file",str(approver_file),
                    "--port",str(port)],stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
                children.append(child)
                ready,_,_=select.select([child.stdout],[],[],5)
                if not ready or "WITNESS_READY" not in child.stdout.readline():
                    raise RuntimeError("witness process startup failed")
                base="http://127.0.0.1:%d"%port
                urls.append(base+"/latest")
                signed=sign_checkpoint(approver,cp)
                req=urllib.request.Request(base+"/publish",data=json.dumps(signed).encode(),
                    headers={"Content-Type":"application/json"},method="POST")
                with urllib.request.urlopen(req,timeout=3) as response:
                    receipt=json.loads(response.read())
                if receipt["status"]!="PUBLISHED":
                    raise AssertionError("witness publication failed")
                receipts.append(receipt["receipt"])
            (output/"witness_keys.json").write_text(json.dumps(witness_keys,sort_keys=True))
            (output/"attestations.json").write_text(json.dumps(receipts,sort_keys=True))
            def check():
                return verify_live(output,output/"manifest.json",sha(manifest),
                    output/"history.sqlite",public_hex(approver),output/"checkpoint.json",
                    digest(cp),1,output/"witness_keys.json",output/"attestations.json",2,urls)
            accepted=check()
            controls["signed_history_live_quorum_accepted"]=accepted
            altered=json.loads((output/"attestations.json").read_text())
            altered[0]["signature"]="00"*64
            (output/"attestations.json").write_text(json.dumps(altered))
            controls["forged_publication_attestation_rejected"]=not check()
            (output/"attestations.json").write_text(json.dumps(receipts))
            children[0].kill()
            children[0].wait(timeout=3)
            controls["witness_process_outage_rejected"]=not check()
        finally:
            for child in children:
                if child.poll() is None:
                    child.terminate()
            for child in children:
                try:
                    child.communicate(timeout=3)
                except subprocess.TimeoutExpired:
                    child.kill()
                    child.communicate(timeout=3)
    result={"schema":"AML-SEF2-LIVE-WITNESS-DEMO-V1","synthetic_only":True,
        "external_independence_proven":False,"controls":controls,
        "manifest_sha256":sha(manifest),"checkpoint_sha256":digest(cp),
        "approver_public_hex":public_hex(approver),
        "witness_public_keys":witness_keys,
        "result":"PASS" if all(controls.values()) else "FAIL"}
    (output/"live-demo-report.json").write_text(json.dumps(result,sort_keys=True,indent=2)+"\n")
    if result["result"]!="PASS":
        raise AssertionError("live witness demo controls failed")
    return result

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--output",required=True)
    a=p.parse_args()
    print(json.dumps(execute(a.output),sort_keys=True,indent=2))
