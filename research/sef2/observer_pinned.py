"""Strict persistent witness identity for synthetic provider-origin events.

Both provider and witness public keys are caller-pinned. Witness private key
is supplied via a separate local file, not generated by untrusted event input.
"""
import argparse
import hashlib
import json
import pathlib
import sys
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from origin_event import OriginVerifier
from signed_receipt import issue, key_id, canonical
from observer_authenticated import load_json

def read_pin(path):
    raw = pathlib.Path(path).read_text(encoding="ascii").strip()
    if len(raw) != 64:
        raise ValueError("invalid public key pin")
    return Ed25519PublicKey.from_public_bytes(bytes.fromhex(raw))

def observe(event_path, provider_pin_path, ledger_path, provider_id,
            witness_private_path, witness_pin_path):
    provider_public = read_pin(provider_pin_path)
    witness_public = read_pin(witness_pin_path)
    secret = pathlib.Path(witness_private_path).read_text(encoding="ascii").strip()
    if len(secret) != 64:
        raise ValueError("invalid witness private key")
    witness_key = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(secret))
    if key_id(witness_key.public_key()) != key_id(witness_public):
        raise ValueError("witness identity pin mismatch")
    if key_id(witness_public) == key_id(provider_public):
        raise ValueError("provider and witness keys must differ")
    envelope = load_json(event_path)
    verifier = OriginVerifier(ledger_path, {provider_id: provider_public})
    verdict = verifier.accept(envelope)
    if verdict != "AUTHENTICATED_SYNTHETIC_EVENT":
        raise ValueError("origin rejected: " + verdict)
    event = envelope["event"]
    evidence = hashlib.sha256(canonical(event["synthetic_effect"])).hexdigest()
    receipt = issue(witness_key, "witness", event["operation_id"],
        event["request_sha256"], "OBSERVED_SYNTHETIC_EFFECT", evidence)
    return {"receipt": receipt, "witness_key_id": key_id(witness_public),
        "provider_key_id": key_id(provider_public),
        "origin_verdict": verdict, "persistent_witness_identity": True,
        "independent_source_proven": False, "external_execution_proven": False}

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    for flag in ("event", "provider-public-key-file", "replay-db", "provider-id",
                 "witness-private-key-file", "witness-public-key-file"):
        p.add_argument("--" + flag, required=True)
    a = vars(p.parse_args())
    try:
        print(json.dumps(observe(a["event"], a["provider_public_key_file"],
            a["replay_db"], a["provider_id"], a["witness_private_key_file"],
            a["witness_public_key_file"]), sort_keys=True))
    except (ValueError, OSError, TypeError, json.JSONDecodeError) as exc:
        print("pinned witness rejected: " + str(exc), file=sys.stderr)
        sys.exit(2)
